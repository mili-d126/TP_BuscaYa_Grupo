create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_rol_id bigint;
begin
    select id into v_rol_id
    from public.roles
    where codigo = 'usuario';

    if v_rol_id is null then
        raise exception 'No existe el rol inicial usuario';
    end if;

    insert into public.usuarios (id, rol_id, nombre, email)
    values (
        new.id,
        v_rol_id,
        coalesce(new.raw_user_meta_data ->> 'nombre', split_part(new.email, '@', 1)),
        new.email
    );
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

create or replace function public.handle_updated_user_email()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.usuarios set email = new.email where id = new.id;
    return new;
end;
$$;

drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
    after update of email on auth.users
    for each row execute function public.handle_updated_user_email();

