create table if not exists public.roles (
    id bigint generated by default as identity primary key,
    codigo text not null unique,
    nombre text not null unique
);

create table if not exists public.usuarios (
    id uuid primary key references auth.users (id) on delete cascade,
    rol_id bigint not null references public.roles (id),
    nombre text not null,
    email text not null unique,
    telefono text,
    foto_perfil text default 'default.jpg'
);

create table if not exists public.tipos_reporte (
    id bigint generated by default as identity primary key,
    codigo text not null unique,
    nombre text not null unique
);

create table if not exists public.categorias (
    id bigint generated by default as identity primary key,
    codigo text not null unique,
    nombre text not null unique
);

create table if not exists public.estados_reporte (
    id bigint generated by default as identity primary key,
    codigo text not null unique,
    nombre text not null unique
);

create table if not exists public.reportes (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references public.usuarios (id) on delete cascade,
    tipo_reporte_id bigint not null references public.tipos_reporte (id),
    categoria_id bigint not null references public.categorias (id),
    estado_id bigint not null references public.estados_reporte (id),
    titulo text not null,
    descripcion text,
    lugar text,
    latitud double precision not null check (latitud between -90 and 90),
    longitud double precision not null check (longitud between -180 and 180),
    fecha date not null,
    creado_en timestamptz not null default now()
);

create table if not exists public.archivos_adjuntos (
    id bigint generated by default as identity primary key,
    reporte_id bigint not null references public.reportes (id) on delete cascade,
    ruta_storage text not null unique,
    nombre_archivo text,
    tipo_mime text,
    subido_en timestamptz not null default now()
);

create table if not exists public.comentarios (
    id bigint generated by default as identity primary key,
    reporte_id bigint not null references public.reportes (id) on delete cascade,
    usuario_id uuid not null references public.usuarios (id) on delete cascade,
    contenido text not null,
    creado_en timestamptz not null default now()
);

