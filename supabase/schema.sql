create table if not exists public.usuarios (
    id uuid primary key references auth.users (id) on delete cascade,
    nombre text not null,
    email text not null,
    telefono text,
    foto_perfil text default 'default.jpg'
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.usuarios (id, nombre, email)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'nombre', split_part(new.email, '@', 1)),
        new.email
    );
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

create or replace function public.handle_updated_user_email()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.usuarios set email = new.email where id = new.id;
    return new;
end;
$$;

drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
    after update of email on auth.users
    for each row execute function public.handle_updated_user_email();

create table if not exists public.reportes (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references public.usuarios (id) on delete cascade,
    tipo text not null check (tipo in ('perdido', 'encontrado')),
    titulo text not null,
    descripcion text,
    categoria text,
    lugar text,
    latitud double precision not null check (latitud between -90 and 90),
    longitud double precision not null check (longitud between -180 and 180),
    fecha date not null,
    foto text,
    estado text not null default 'activo' check (estado in ('activo', 'resuelto')),
    creado_en timestamptz not null default now()
);

create index if not exists reportes_usuario_id_idx on public.reportes (usuario_id);
create index if not exists reportes_estado_creado_en_idx on public.reportes (estado, creado_en desc);

grant usage on schema public to authenticated;
grant select on public.usuarios to authenticated;
grant update (telefono, foto_perfil) on public.usuarios to authenticated;
grant select, insert, update, delete on public.reportes to authenticated;
grant usage, select on sequence public.reportes_id_seq to authenticated;

alter table public.usuarios enable row level security;
alter table public.reportes enable row level security;

drop policy if exists "Authenticated users can view profiles" on public.usuarios;
create policy "Authenticated users can view profiles"
    on public.usuarios for select to authenticated
    using (true);

drop policy if exists "Users can update their own profile" on public.usuarios;
create policy "Users can update their own profile"
    on public.usuarios for update to authenticated
    using (id = (select auth.uid()))
    with check (id = (select auth.uid()));

drop policy if exists "Users can view active or their own reports" on public.reportes;
create policy "Users can view active or their own reports"
    on public.reportes for select to authenticated
    using (estado = 'activo' or usuario_id = (select auth.uid()));

drop policy if exists "Users can create their own reports" on public.reportes;
create policy "Users can create their own reports"
    on public.reportes for insert to authenticated
    with check (usuario_id = (select auth.uid()));

drop policy if exists "Users can update their own reports" on public.reportes;
create policy "Users can update their own reports"
    on public.reportes for update to authenticated
    using (usuario_id = (select auth.uid()))
    with check (usuario_id = (select auth.uid()));

drop policy if exists "Users can delete their own reports" on public.reportes;
create policy "Users can delete their own reports"
    on public.reportes for delete to authenticated
    using (usuario_id = (select auth.uid()));

